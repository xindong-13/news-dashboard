# 長的先換，避免「信息安全」被「信息」先換掉
_GLOSSARY = sorted(GLOSSARY, key=lambda kv: len(kv[0]), reverse=True)


@lru_cache(maxsize=1)
def _s2tw() -> opencc.OpenCC:
    return opencc.OpenCC("s2tw")


def to_taiwan(text: str) -> str:
    """簡體轉繁體字形，再換成台灣用語。已經是繁體的文字也可以安全套用。"""
    if not text:
        return text
    out = _s2tw().convert(text).replace("臺", "台")
    for cn, tw in _GLOSSARY:
        if cn in out:
            out = out.replace(cn, tw)
    return out
